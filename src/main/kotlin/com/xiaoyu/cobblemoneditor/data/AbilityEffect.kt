package com.xiaoyu.cobblemoneditor.data

/** 触发时机：决定效果积木生成到哪个 Showdown 事件处理器。 */
enum class AbilityTrigger(
    val handler: String,
    val params: String,
    val displayName: String,
) {
    ON_START("onStart", "pokemon", "出场/战斗开始"),
    ON_BEFORE_MOVE("onBeforeMove", "source, target, move", "招式发动前"),
    ON_RESIDUAL("onResidual", "pokemon", "回合结束"),
    ON_TRY_HIT("onTryHit", "target, source, move", "受到攻击时(免疫)"),
    ON_DAMAGING_HIT("onDamagingHit", "damage, target, source, move", "受到伤害后"),
    ON_BASE_POWER("onBasePower", "basePower, attacker, defender, move", "威力计算时"),
    ON_UPDATE("onUpdate", "pokemon", "每回合检查"),
    ON_MODIFY_ATK("onModifyAtk", "atk, attacker, defender, move", "物攻计算时"),
    ON_MODIFY_DEF("onModifyDef", "def, defender, attacker, move", "物防计算时"),
    ON_MODIFY_SPA("onModifySpA", "spa, attacker, defender, move", "特攻计算时"),
    ON_MODIFY_SPD("onModifySpD", "spd, defender, attacker, move", "特防计算时"),
    ON_MODIFY_SPE("onModifySpe", "spe, pokemon", "速度计算时"),
    ON_SET_STATUS("onSetStatus", "status, target, source, effect", "获得异常状态时"),
    ON_FOE_MAYBE_TRAP_POKEMON("onFoeMaybeTrapPokemon", "pokemon, source", "对手逃跑判定时"),
    ON_SOURCE_MODIFY_DAMAGE("onSourceModifyDamage", "damage, source, target, move", "承受伤害修正时"),
    ON_SWITCH_IN("onSwitchIn", "pokemon", "换入时"),
    ON_MODIFY_PRIORITY("onModifyPriority", "priority, pokemon, target, move", "先制度计算时"),
    ON_MODIFY_ACCURACY("onModifyAccuracy", "accuracy, target, source, move", "命中率计算时"),
    ON_MODIFY_SECONDARIES("onModifySecondaries", "secondaries, target, source, move", "附加效果结算时"),
    ON_WEATHER("onWeather", "target, source, effect", "天气结算时"),
    ON_CHANGE_BOOST("onChangeBoost", "boost, target, source, effect", "能力变化结算时"),
    ON_TRY_BOOST("onTryBoost", "boost, target, source, effect", "能力变化尝试时"),
    ON_TAKE_ITEM("onTakeItem", "item, pokemon, source", "道具被夺时"),
    ON_MODIFY_MOVE("onModifyMove", "move, pokemon, target, move", "招式修正时"),
    ON_MODIFY_CRIT_RATIO("onModifyCritRatio", "critRatio, source, target, move", "会心等级计算时"),
    ON_SOURCE_AFTER_FAINT("onSourceAfterFaint", "length, target, source, effect", "击倒对手后"),
}

